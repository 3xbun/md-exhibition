#!/usr/bin/env node
// Auto-version stamp. Runs before every `vite build` (prebuild) and before
// `vite` (dev). Identifies the code being built by its git commit:
//   version = YY-<shortSHA>  (e.g. 26-f816d06 = year 2026, commit f816d06)
// On Cloudflare Pages the commit is taken from CF_PAGES_COMMIT_SHA (injected
// at build time), so the deployed footer always shows the EXACT commit that
// deployment is running — no manual counter, nothing to commit.
// Writes src/version.js (bundled). Both it and .build-counter are untracked;
// they are build artifacts, not source.
import { writeFileSync, existsSync } from "fs";
import path from "path";
import { execSync } from "child_process";
import { fileURLToPath } from "url";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const versionPath = path.join(root, "src", "version.js");

const now = new Date();
const yy = String(now.getFullYear()).slice(-2);
const iso = now.toISOString();

let id;
// 1) Cloudflare Pages injects the commit SHA at build time.
const cfSha = process.env.CF_PAGES_COMMIT_SHA;
// 2) Local: current git HEAD.
let gitSha = "";
try {
  gitSha = execSync("git rev-parse --short HEAD", {
    cwd: root,
    stdio: ["ignore", "pipe", "ignore"],
  })
    .toString()
    .trim();
} catch {
  /* not a git checkout */
}
id = (cfSha || gitSha || "dev").slice(0, 7);

const version = `${yy}-${id}`;

writeFileSync(
  versionPath,
  `// AUTO-GENERATED by scripts/version.mjs (do not edit by hand; not committed).\n` +
    `// format: YY-<commit> - ${yy} = year ${yy}, <commit> = short git SHA of what is deployed\n` +
    `export const version = ${JSON.stringify(version)};\n` +
    `export const buildStamp = ${JSON.stringify(iso)};\n`
);

console.log(`v${version} (built ${iso})`);

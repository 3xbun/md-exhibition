#!/usr/bin/env node
// Auto-version stamp. Runs before every `vite build` (prebuild).
// version = YY.BUILD  (e.g. 26.1 = year 2026, build 1)
//  - YY   : last two digits of the current year, derived at build time
//  - BUILD: auto-incremented counter persisted in .build-counter (committed)
// Writes src/version.js (bundled) + dist/build-stamp.json if dist exists yet.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "fs";
import path from "path";
import { fileURLToPath } from "url";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const counterPath = path.join(root, ".build-counter");
const versionPath = path.join(root, "src", "version.js");

const now = new Date();
const yy = String(now.getFullYear()).slice(-2);

let build = 1;
if (existsSync(counterPath)) {
  const cur = parseInt(readFileSync(counterPath, "utf8").trim(), 10);
  build = Number.isFinite(cur) && cur > 0 ? cur + 1 : 1;
}

const version = `${yy}.${build}`;
const iso = now.toISOString();

writeFileSync(counterPath, String(build).padStart(3, "0"));
writeFileSync(
  versionPath,
  `// AUTO-GENERATED by scripts/version.mjs (do not edit by hand).\n` +
    `// format: YY.BUILD - ${yy} = year ${yy}, build ${build}\n` +
    `export const version = ${JSON.stringify(version)};\n` +
    `export const buildStamp = ${JSON.stringify(iso)};\n`
);

console.log(`v${version} (built ${iso})`);
